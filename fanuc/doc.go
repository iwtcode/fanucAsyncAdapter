// Package fanuc — клиент FOCAS2 Ethernet для ЧПУ FANUC и эмулятора FANUC CNC GUIDE.
//
// Cgo не нужен: Fwlib32.dll / Fwlib64.dll загружаются напрямую через syscall,
// поэтому пакет работает только в Windows (на других ОС он компилируется, но
// Connect возвращает ErrUnsupportedPlatform).
//
// Пример:
//
//	c, err := fanuc.Connect(fanuc.Config{IP: "127.0.0.1", Port: 8193})
//	if err != nil {
//		log.Fatal(err)
//	}
//	defer c.Close()
//
//	info, _ := c.ProgramInfo()    // состояние станка, имя/номер программы, текущий кадр
//	axes, _ := c.Axes()           // позиции осей
//	prog, _ := c.RunningProgram() // полный текст выполняемой управляющей программы
//
// # Потоки
//
// Библиотека FOCAS привязывает handle соединения к потоку ОС, в котором он
// был получен. Рантайм Go может перенести горутину на другой поток, и тогда
// любая функция FOCAS отвечает EW_HANDLE (-8). Поэтому Client держит одну
// выделенную горутину, закреплённую за потоком ОС (runtime.LockOSThread), и
// выполняет в ней все вызовы. Методы Client безопасны для вызова из любого
// числа горутин одновременно — вызовы выстраиваются в очередь.
